import { colors, fonts, motion, radius, typeScale, type ColorScheme } from './tokens';

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function colorVars(scheme: ColorScheme): string {
  return Object.entries(scheme)
    .map(([k, v]) => `  --color-${kebab(k)}: ${v};`)
    .join('\n');
}

/**
 * Generate the web token stylesheet. Tailwind v4 reads the @theme block, so utilities like
 * `bg-surface`, `text-text-muted`, `font-display` and `rounded-control` come straight from
 * these tokens. Dark mode follows the OS unless `data-theme` on <html> overrides it.
 */
export function buildTokenCss(): string {
  const type = Object.entries(typeScale)
    .map(
      ([k, v]) =>
        `  --text-${k}: ${v.size / 16}rem;\n  --text-${k}--line-height: ${v.lineHeight};\n  --text-${k}--letter-spacing: ${v.tracking / 16}rem;`,
    )
    .join('\n');

  return `/* Generated by packages/ui/scripts/build-css.ts from src/tokens.ts. Do not edit. */
@theme {
${colorVars(colors.light)}
  --font-display: "${fonts.display.family}", ${fonts.display.fallback};
  --font-sans: "${fonts.sans.family}", ${fonts.sans.fallback};
${type}
  --radius-control: ${radius.control}px;
  --radius-sheet: ${radius.sheet}px;
  --radius-pill: ${radius.pill}px;
  --ease-settle: ${motion.easing};
  --duration-quick: ${motion.quick}ms;
  --duration-settle: ${motion.settle}ms;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars(colors.dark).replace(/^ {2}/gm, '    ')}
  }
}

:root[data-theme="dark"] {
${colorVars(colors.dark)}
}

@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
}
`;
}
